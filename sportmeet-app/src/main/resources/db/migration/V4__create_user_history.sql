-- Per-attribute change history of accounts (T_USER).
-- IMPORTANT: Do not modify this migration once it has been applied to a shared database.
CREATE TABLE T_USER_HISTORY
(
    ID              BIGINT GENERATED ALWAYS AS IDENTITY NOT NULL,
    USER_ID         BIGINT                              NOT NULL,
    CHANGED_BY      BIGINT,
    CHANGED_BY_TYPE VARCHAR(32)                         NOT NULL,
    ATTRIBUTE_NAME  VARCHAR(100)                        NOT NULL,
    OLD_VALUE       TEXT,
    NEW_VALUE       TEXT,
    CHANGED_AT      TIMESTAMP(6) WITH TIME ZONE         NOT NULL,
    CONSTRAINT PK_T_USER_HISTORY PRIMARY KEY (ID),
    CONSTRAINT FK_T_USER_HISTORY_USER FOREIGN KEY (USER_ID) REFERENCES T_USER (ID),
    CONSTRAINT FK_T_USER_HISTORY_ACTOR FOREIGN KEY (CHANGED_BY) REFERENCES T_USER (ID),
    CONSTRAINT CK_T_USER_HISTORY_ACTOR_TYPE CHECK (CHANGED_BY_TYPE IN ('USER', 'SYSTEM')),
    CONSTRAINT CK_T_USER_HISTORY_ACTOR CHECK
        ((CHANGED_BY_TYPE = 'USER' AND CHANGED_BY IS NOT NULL)
            OR (CHANGED_BY_TYPE = 'SYSTEM' AND CHANGED_BY IS NULL)),
    CONSTRAINT CK_T_USER_HISTORY_ATTRIBUTE CHECK (ATTRIBUTE_NAME IN ('DISPLAY_NAME', 'EMAIL', 'PASSWORD', 'STATE')),
    CONSTRAINT CK_T_USER_HISTORY_PASSWORD CHECK
        (ATTRIBUTE_NAME <> 'PASSWORD' OR (OLD_VALUE IS NULL AND NEW_VALUE IS NULL))
);

CREATE INDEX IX_T_USER_HISTORY_USER_DATE ON T_USER_HISTORY (USER_ID, CHANGED_AT DESC, ID DESC);
CREATE INDEX IX_T_USER_HISTORY_CHANGED_BY ON T_USER_HISTORY (CHANGED_BY);
