-- Sports groups and user memberships in them (module sportmeet-group).
-- Based on the KAN-48 database design, adapted to the conventions of the existing schema:
-- T_ prefix, DataInfo audit columns (CREATED_*/MODIFIED_*), VERSION and named constraints.
-- Membership rules that need partial unique indexes are PostgreSQL-specific and live in
-- db/vendor/postgresql/V5_1__create_group_membership_rules.sql.
-- IMPORTANT: Do not modify this migration once it has been applied to a shared database.
CREATE TABLE T_GROUP
(
    ID                      BIGINT GENERATED ALWAYS AS IDENTITY NOT NULL,
    NAME                    VARCHAR(100)                        NOT NULL,
    DESCRIPTION             TEXT,
    VISIBILITY              VARCHAR(32)                         NOT NULL,
    VALID                   BOOLEAN DEFAULT TRUE                NOT NULL,
    CREATED_AT              TIMESTAMP(6) WITH TIME ZONE         NOT NULL,
    CREATED_BY_OBJECT_ID    BIGINT,
    CREATED_BY_OBJECT_TYPE  VARCHAR(32)                         NOT NULL,
    MODIFIED_AT             TIMESTAMP(6) WITH TIME ZONE,
    MODIFIED_BY_OBJECT_ID   BIGINT,
    MODIFIED_BY_OBJECT_TYPE VARCHAR(32),
    VERSION                 BIGINT                              NOT NULL,
    CONSTRAINT PK_T_GROUP PRIMARY KEY (ID),
    CONSTRAINT FK_T_GROUP_CREATED_BY FOREIGN KEY (CREATED_BY_OBJECT_ID) REFERENCES T_USER (ID),
    CONSTRAINT FK_T_GROUP_MODIFIED_BY FOREIGN KEY (MODIFIED_BY_OBJECT_ID) REFERENCES T_USER (ID),
    CONSTRAINT CK_T_GROUP_NAME CHECK (TRIM(NAME) <> ''),
    CONSTRAINT CK_T_GROUP_VISIBILITY CHECK (VISIBILITY IN ('PUBLIC', 'PRIVATE')),
    CONSTRAINT CK_T_GROUP_CREATED_BY CHECK
        ((CREATED_BY_OBJECT_TYPE = 'USER' AND CREATED_BY_OBJECT_ID IS NOT NULL)
            OR (CREATED_BY_OBJECT_TYPE = 'SYSTEM' AND CREATED_BY_OBJECT_ID IS NULL)),
    CONSTRAINT CK_T_GROUP_MODIFIED_BY CHECK
        ((MODIFIED_BY_OBJECT_TYPE IS NULL AND MODIFIED_BY_OBJECT_ID IS NULL AND MODIFIED_AT IS NULL)
            OR (MODIFIED_BY_OBJECT_TYPE = 'USER' AND MODIFIED_BY_OBJECT_ID IS NOT NULL AND MODIFIED_AT IS NOT NULL)
            OR (MODIFIED_BY_OBJECT_TYPE = 'SYSTEM' AND MODIFIED_BY_OBJECT_ID IS NULL AND MODIFIED_AT IS NOT NULL))
);

-- Membership of a user in a group. Ended memberships stay as history (STATUS = 'ENDED');
-- VALID = FALSE marks a record that does not apply at all (for example created by mistake).
-- The join time is CREATED_AT: a membership record is always created when the user joins.
CREATE TABLE T_GROUP_MEMBERSHIP
(
    ID                      BIGINT GENERATED ALWAYS AS IDENTITY NOT NULL,
    GROUP_ID                BIGINT                              NOT NULL,
    USER_ID                 BIGINT                              NOT NULL,
    ROLE                    VARCHAR(32)                         NOT NULL,
    STATUS                  VARCHAR(32)                         NOT NULL,
    ENDED_AT                TIMESTAMP(6) WITH TIME ZONE,
    VALID                   BOOLEAN DEFAULT TRUE                NOT NULL,
    CREATED_AT              TIMESTAMP(6) WITH TIME ZONE         NOT NULL,
    CREATED_BY_OBJECT_ID    BIGINT,
    CREATED_BY_OBJECT_TYPE  VARCHAR(32)                         NOT NULL,
    MODIFIED_AT             TIMESTAMP(6) WITH TIME ZONE,
    MODIFIED_BY_OBJECT_ID   BIGINT,
    MODIFIED_BY_OBJECT_TYPE VARCHAR(32),
    VERSION                 BIGINT                              NOT NULL,
    CONSTRAINT PK_T_GROUP_MEMBERSHIP PRIMARY KEY (ID),
    CONSTRAINT FK_T_GROUP_MEMBERSHIP_GROUP FOREIGN KEY (GROUP_ID) REFERENCES T_GROUP (ID),
    CONSTRAINT FK_T_GROUP_MEMBERSHIP_USER FOREIGN KEY (USER_ID) REFERENCES T_USER (ID),
    CONSTRAINT FK_T_GROUP_MEMBERSHIP_CREATED_BY FOREIGN KEY (CREATED_BY_OBJECT_ID) REFERENCES T_USER (ID),
    CONSTRAINT FK_T_GROUP_MEMBERSHIP_MODIFIED_BY FOREIGN KEY (MODIFIED_BY_OBJECT_ID) REFERENCES T_USER (ID),
    CONSTRAINT CK_T_GROUP_MEMBERSHIP_ROLE CHECK (ROLE IN ('OWNER', 'SECONDARY_OWNER', 'MEMBER')),
    CONSTRAINT CK_T_GROUP_MEMBERSHIP_STATUS CHECK (STATUS IN ('ACTIVE', 'ENDED')),
    CONSTRAINT CK_T_GROUP_MEMBERSHIP_ENDED CHECK
        ((STATUS = 'ACTIVE' AND ENDED_AT IS NULL)
            OR (STATUS = 'ENDED' AND ENDED_AT IS NOT NULL AND ENDED_AT >= CREATED_AT)),
    CONSTRAINT CK_T_GROUP_MEMBERSHIP_CREATED_BY CHECK
        ((CREATED_BY_OBJECT_TYPE = 'USER' AND CREATED_BY_OBJECT_ID IS NOT NULL)
            OR (CREATED_BY_OBJECT_TYPE = 'SYSTEM' AND CREATED_BY_OBJECT_ID IS NULL)),
    CONSTRAINT CK_T_GROUP_MEMBERSHIP_MODIFIED_BY CHECK
        ((MODIFIED_BY_OBJECT_TYPE IS NULL AND MODIFIED_BY_OBJECT_ID IS NULL AND MODIFIED_AT IS NULL)
            OR (MODIFIED_BY_OBJECT_TYPE = 'USER' AND MODIFIED_BY_OBJECT_ID IS NOT NULL AND MODIFIED_AT IS NOT NULL)
            OR (MODIFIED_BY_OBJECT_TYPE = 'SYSTEM' AND MODIFIED_BY_OBJECT_ID IS NULL AND MODIFIED_AT IS NOT NULL))
);

CREATE INDEX IX_T_GROUP_MEMBERSHIP_GROUP ON T_GROUP_MEMBERSHIP (GROUP_ID);
CREATE INDEX IX_T_GROUP_MEMBERSHIP_USER ON T_GROUP_MEMBERSHIP (USER_ID);
